/**
 * "ביקשתי סטטוס טיפול של כל הבוגרים — קיבלתי רק פילוח לפי בית ספר" (מיטל, 5.9).
 *
 * הפיצ'ר ששולח למקום הנכון היה קיים, אבל נדלק רק כשהמשפט לא הזכיר **אף**
 * עמודה מקומית. משפט שמערבב דבר שקיים כאן עם דבר שלא — סיפק את התנאי, והחצי
 * החסר נפל בשקט. הבדיקה עברה מרמת המשפט לרמת העמודה.
 */
import { describe, it, expect } from "vitest";
import { askedForElsewhere } from "../board-profile";

const OTHERS = [
  { boardId: "b2", boardName: "בוגרי בית הערבה", titles: ["שם", "סטטוס טיפול", "מלגה"] },
  { boardId: "b3", boardName: "בוגרי עכו", titles: ["שם", "סטטוס טיפול"] },
];

describe("askedForElsewhere", () => {
  it("המקרה של מיטל: משפט שמערבב עמודה שקיימת עם אחת שלא — מדווח על החסרה", () => {
    const hits = askedForElsewhere(
      "סטטוס הטיפול של כל הבוגרים לפי בית ספר",
      ["שם מלא", "בית ספר", "עיר", "שנת סיום"],
      OTHERS
    );
    expect(hits.map((h) => h.column)).toContain("סטטוס טיפול");
  });

  it("לא מדווח על מה שהלוח הזה כן יודע לענות", () => {
    const hits = askedForElsewhere("פילוח לפי בית ספר", ["בית ספר"], [
      { boardId: "b2", boardName: "אחר", titles: ["בית ספר"] },
    ]);
    expect(hits).toHaveLength(0);
  });

  it("עמודה שקיימת כאן בשם דומה נחשבת זמינה, ולא מדווחת כחסרה", () => {
    const hits = askedForElsewhere("מה סטטוס הטיפול?", ["סטטוס"], OTHERS);
    expect(hits).toHaveLength(0);
  });

  /* הטסט הזה נעל בגרסה הראשונה את ההתנהגות ההפוכה — "מדווחת פעם אחת" — והוא
     היה פשוט שגוי. מיטל תפסה את זה על נתונים אמיתיים: "מה עושה היום" קיימת
     בלוח של כל בית ספר, והמערכת אמרה לה שהיא קיימת בלוח אחד.

     המניין הזה הוא לא קוסמטיקה: הוא מה שמבדיל בין "לך ללוח ההוא" לבין ההצעה
     האמיתית — להציג את העמודה מכל הלוחות יחד, בפילוח לפי לוח. כשכל לוח הוא
     בית ספר, ההצעה הזו היא בדיוק מה שהיא ביקשה. */
  it("עמודה שקיימת בכמה לוחות מדווחת פעם לכל לוח — זה מה שמפעיל את ההצעה החוצה-לוחות", () => {
    const hits = askedForElsewhere("מה הבוגרים עושים היום", ["עיר"], [
      { boardId: "b2", boardName: "בוגרי בית הערבה", titles: ["שם", "מה עושה היום"] },
      { boardId: "b3", boardName: "בוגרי עכו", titles: ["שם", "מה עושה היום"] },
      { boardId: "b4", boardName: "בוגרי אשקלון", titles: ["מה עושה היום"] },
    ]);
    expect(hits).toHaveLength(3);
    expect(new Set(hits.map((h) => h.boardId)).size).toBe(3);
    expect(hits.every((h) => h.column === "מה עושה היום")).toBe(true);
  });

  it("לוח אחד לא מדווח פעמיים, גם אם כמה מעמודותיו מתאימות", () => {
    const hits = askedForElsewhere("סטטוס טיפול ומלגה", ["עיר"], [
      { boardId: "b2", boardName: "בוגרי בית הערבה", titles: ["סטטוס טיפול", "מלגה"] },
    ]);
    expect(hits).toHaveLength(1);
  });

  it("משפט ריק או כללי לא מייצר רעש", () => {
    expect(askedForElsewhere("", ["עיר"], OTHERS)).toHaveLength(0);
    expect(askedForElsewhere("שיהיה יפה", ["עיר"], OTHERS)).toHaveLength(0);
  });
});

/* ── איזו כתיב של הבקשה נשלחת לכל הלוחות ────────────────────────────────────
   חיתוך חוצה-לוחות נושא **שם עמודה אחד** ומתאים אותו מחדש לכל לוח. לכן השם
   שנבחר קובע כמה לוחות בכלל יוכלו לענות.

   הכלל הראשון שכתבתי היה "הכותרת הקצרה ביותר היא הקנונית". מיטל, 5.9: לוח אחד
   עם עמודה בשם "היום" ניצח חמישה עם "מה עושה היום", והדשבורד יצא בשם "היום"
   לפי לוח עם אזהרה שנמצאה בפחות משני לוחות. */
import { canonicalColumn } from "../board-profile";

describe("canonicalColumn — הכתיב שמגיע לכי הרבה לוחות", () => {
  const SCHOOLS = [
    { titles: ["שם", "מה עושה היום"] },
    { titles: ["שם", "מה עושה היום"] },
    { titles: ["מה עושה היום", "עיר"] },
    { titles: ["מה עושה היום"] },
    { titles: ["מה עושה היום"] },
    { titles: ["היום"] },
  ];

  it("המקרה של מיטל: לא בוחר את 'היום' רק כי הוא קצר", () => {
    expect(canonicalColumn(["מה עושה היום", "היום"], SCHOOLS)).toBe("מה עושה היום");
  });

  it("סדר המועמדים לא משנה — ההכרעה היא כמה לוחות מגיעים", () => {
    expect(canonicalColumn(["היום", "מה עושה היום"], SCHOOLS)).toBe("מה עושה היום");
  });

  it("בתיקו נבחרת הכותרת הארוכה — המפורשת מבין השתיים", () => {
    const both = [{ titles: ["סטטוס"] }, { titles: ["סטטוס טיפול"] }];
    expect(canonicalColumn(["סטטוס טיפול", "סטטוס"], both)).toBe("סטטוס טיפול");
  });

  it("בלי מועמדים — null, ולא ניחוש", () => {
    expect(canonicalColumn([], SCHOOLS)).toBeNull();
    expect(canonicalColumn(["  "], SCHOOLS)).toBeNull();
  });
});

/* לוח שיש בו שתי כותרות שמתאימות תורם את שתיהן כמועמדות. `find` החזיר רק את
   הראשונה בסדר העמודות, ולכן "מה עושה היום" לא הגיע בכלל להכרעה — הבקשה יצאה
   בשם "היום". כותרת שלא נאספה היא כותרת שלא יכולה לנצח. */
describe("askedForElsewhere — כל הכותרות המתאימות, לא רק הראשונה", () => {
  it("לוח עם שתי כותרות מתאימות מציע את שתיהן", () => {
    const [hit] = askedForElsewhere("מה הבוגרים עושים היום", ["עיר"], [
      { boardId: "b2", boardName: "בוגרי עכו", titles: ["היום", "מה עושה היום"] },
    ]);
    expect(hit.columns).toEqual(["היום", "מה עושה היום"]);
  });

  it("והכותרת המפורשת היא שנבחרת בסוף — לא זו שבמקרה ראשונה", () => {
    const boards = [
      { boardId: "b2", boardName: "עכו", titles: ["היום", "מה עושה היום"] },
      { boardId: "b3", boardName: "אשקלון", titles: ["היום", "מה עושה היום"] },
    ];
    const hits = askedForElsewhere("מה הבוגרים עושים היום", ["עיר"], boards);
    const chosen = canonicalColumn(hits.flatMap((h) => h.columns), boards);
    expect(chosen).toBe("מה עושה היום");
  });
});

/* הכותרות האמיתיות מחשבון ה-Monday של מיטל (5.9), שנקראו כשמות בלבד:
   "מה עושה היום" ב-11 לוחות · "הגיע/לא הגיע - היום לבית ספר" ב-2 ·
   "היום" (תאריך) ב-2 · ועוד שתי כותרות שאלה שמכילות "היום".

   המדד הקודם — "כמה לוחות הכותרת מגיעה אליהם" — נתן ל"היום" 17 ול"מה עושה
   היום" 13, כי מילה קצרה וגנרית מוכלת בתוך כל כותרת ארוכה. מדד שמתגמל
   עמימות. הכלל עכשיו: כמה לוחות באמת קוראים לעמודה שלהם ככה. */
describe("canonicalColumn — החשבון האמיתי של מיטל", () => {
  const REAL = [
    ...Array(11).fill({ titles: ["שם", "מה עושה היום"] }),
    ...Array(2).fill({ titles: ["הגיע/לא הגיע - היום לבית ספר"] }),
    ...Array(2).fill({ titles: ["היום"] }),
    { titles: ["איפה רשימת הבוגרים מנוהלת היום?"] },
    { titles: ["עם כמה מהם יש לכם קשר כלשהו היום?"] },
  ];

  it("בוחר את מה ש-11 לוחות באמת קוראים לעמודה שלהם, לא את המילה שמוכלת בכולן", () => {
    const candidates = [
      "מה עושה היום", "היום", "הגיע/לא הגיע - היום לבית ספר",
      "איפה רשימת הבוגרים מנוהלת היום?", "עם כמה מהם יש לכם קשר כלשהו היום?",
    ];
    expect(canonicalColumn(candidates, REAL)).toBe("מה עושה היום");
  });

  it("גם כשהמילה הגנרית מופיעה ראשונה ברשימה", () => {
    expect(canonicalColumn(["היום", "מה עושה היום"], REAL)).toBe("מה עושה היום");
  });
});
